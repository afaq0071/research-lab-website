/* ==========================================================================
   MCAA Lab — Main Script
   Small interactions only: theme, mobile menu, scroll effects, filters.
   No HTML is generated by this file. All markup lives in the HTML pages.
   ========================================================================== */

document.addEventListener("DOMContentLoaded", function () {
  "use strict";

  /* ---------- Flag that JS is active (for reveal animations) ---------- */
  document.documentElement.classList.add("js");

  /* ---------- Theme: restore saved choice or follow system ---------- */
  function applyTheme(theme) {
    document.documentElement.setAttribute("data-theme", theme);
  }

  function initTheme() {
    var saved = null;
    try { saved = localStorage.getItem("mcaa-theme"); } catch (e) { /* ignore */ }
    var systemDark = window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches;
    applyTheme(saved || (systemDark ? "dark" : "light"));
  }

  function toggleTheme() {
    var next = document.documentElement.getAttribute("data-theme") === "dark" ? "light" : "dark";
    applyTheme(next);
    try { localStorage.setItem("mcaa-theme", next); } catch (e) { /* ignore */ }
  }

  var themeToggle = document.getElementById("themeToggle");
  if (themeToggle) themeToggle.addEventListener("click", toggleTheme);
  initTheme();

  /* ---------- Mobile menu ---------- */
  var hamburger = document.getElementById("hamburger");
  var mobileNav = document.getElementById("mobileNav");
  var mobileClose = document.getElementById("mobileClose");

  function closeMobile() {
    if (!mobileNav) return;
    mobileNav.classList.remove("open");
    mobileNav.setAttribute("aria-hidden", "true");
    document.body.classList.remove("nav-lock");
    if (hamburger) hamburger.setAttribute("aria-expanded", "false");
  }

  if (hamburger && mobileNav) {
    hamburger.addEventListener("click", function () {
      mobileNav.classList.add("open");
      mobileNav.setAttribute("aria-hidden", "false");
      document.body.classList.add("nav-lock");
      hamburger.setAttribute("aria-expanded", "true");
    });
  }
  if (mobileClose) mobileClose.addEventListener("click", closeMobile);

  document.querySelectorAll(".mobile-nav a").forEach(function (link) {
    link.addEventListener("click", closeMobile);
  });

  /* ---------- Sticky header shadow ---------- */
  var siteHeader = document.getElementById("siteHeader");

  function onScrollHeader() {
    if (siteHeader) siteHeader.classList.toggle("scrolled", window.scrollY > 8);
  }
  window.addEventListener("scroll", onScrollHeader, { passive: true });
  onScrollHeader();

  /* ---------- Back to top ---------- */
  var toTop = document.getElementById("toTop");

  function onScrollToTop() {
    if (toTop) toTop.classList.toggle("show", window.scrollY > 600);
  }
  window.addEventListener("scroll", onScrollToTop, { passive: true });
  onScrollToTop();

  if (toTop) {
    toTop.addEventListener("click", function () {
      window.scrollTo({ top: 0, behavior: "smooth" });
    });
  }

  /* ---------- Reveal on scroll ---------- */
  var revealEls = document.querySelectorAll(".reveal");
  if ("IntersectionObserver" in window) {
    var revealObserver = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          revealObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });
    revealEls.forEach(function (el) { revealObserver.observe(el); });
  } else {
    revealEls.forEach(function (el) { el.classList.add("visible"); });
  }

  /* ---------- Animated counters ---------- */
  var counters = document.querySelectorAll("[data-count]");

  function animateCount(el) {
    var target = parseFloat(el.getAttribute("data-count")) || 0;
    var suffix = el.getAttribute("data-suffix") || "";
    var duration = 1500;
    var start = null;

    function frame(timestamp) {
      if (!start) start = timestamp;
      var progress = Math.min((timestamp - start) / duration, 1);
      var eased = 1 - Math.pow(1 - progress, 3);
      el.textContent = Math.round(target * eased) + suffix;
      if (progress < 1) {
        requestAnimationFrame(frame);
      } else {
        el.textContent = target + suffix;
      }
    }
    requestAnimationFrame(frame);
  }

  if ("IntersectionObserver" in window && counters.length) {
    var countObserver = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          animateCount(entry.target);
          countObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.4 });
    counters.forEach(function (el) { countObserver.observe(el); });
  }

  /* ---------- Publication filters ---------- */
  var filterButtons = document.querySelectorAll("[data-filter]");
  var pubCards = document.querySelectorAll("[data-category]");
  var pubCount = document.getElementById("pubCount");

  function updatePubCount() {
    if (!pubCount) return;
    var visible = Array.prototype.filter.call(pubCards, function (card) {
      return card.style.display !== "none";
    }).length;
    pubCount.textContent = visible + " of " + pubCards.length + " shown.";
  }

  filterButtons.forEach(function (button) {
    button.addEventListener("click", function () {
      filterButtons.forEach(function (btn) {
        btn.classList.remove("active");
        btn.setAttribute("aria-selected", "false");
      });
      button.classList.add("active");
      button.setAttribute("aria-selected", "true");

      var value = button.getAttribute("data-filter");
      pubCards.forEach(function (card) {
        var category = card.getAttribute("data-category") || "all";
        var show = value === "all" || category === value;
        card.style.display = show ? "" : "none";
      });
      updatePubCount();
    });
  });
  updatePubCount();

  /* Activate a filter from the URL hash (e.g. #journals) */
  var hashMap = { journals: "journal", conferences: "conference", preprints: "preprint" };
  var hashKey = (location.hash || "").replace("#", "");
  var filterToActivate = hashMap[hashKey];
  if (filterToActivate) {
    var targetButton = document.querySelector('[data-filter="' + filterToActivate + '"]');
    if (targetButton) setTimeout(function () { targetButton.click(); }, 60);
  }

  /* ---------- FAQ accordion ---------- */
  document.querySelectorAll(".faq-item").forEach(function (item) {
    var q = item.querySelector(".faq-q");
    var a = item.querySelector(".faq-a");
    if (!q || !a) return;
    q.addEventListener("click", function () {
      var isOpen = item.classList.contains("open");
      document.querySelectorAll(".faq-item.open").forEach(function (openItem) {
        if (openItem !== item) {
          openItem.classList.remove("open");
          var openA = openItem.querySelector(".faq-a");
          var openQ = openItem.querySelector(".faq-q");
          if (openA) openA.style.maxHeight = null;
          if (openQ) openQ.setAttribute("aria-expanded", "false");
        }
      });
      item.classList.toggle("open", !isOpen);
      q.setAttribute("aria-expanded", String(!isOpen));
      a.style.maxHeight = !isOpen ? a.scrollHeight + "px" : null;
    });
  });

  /* ---------- Contact form (demo only, nothing is sent) ---------- */
  var contactForm = document.getElementById("contactForm");
  if (contactForm) {
    var successBox = document.getElementById("formSuccess");
    contactForm.addEventListener("submit", function (event) {
      event.preventDefault();
      if (!contactForm.checkValidity()) {
        contactForm.reportValidity();
        return;
      }
      if (successBox) {
        successBox.classList.add("show");
        successBox.scrollIntoView({ behavior: "smooth", block: "nearest" });
      }
      contactForm.reset();
    });
  }

  /* ---------- Footer year ---------- */
  var yearEl = document.getElementById("year");
  if (yearEl) yearEl.textContent = new Date().getFullYear();
});
